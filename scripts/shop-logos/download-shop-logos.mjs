// Downloads the logos listed in shops.mjs from logo.dev into the app as static files, so the running app makes no
// requests and carries no key. Usage (the publishable key, never committed):
//   LOGO_DEV_TOKEN=pk_... node scripts/shop-logos/download-shop-logos.mjs [--force]
// Existing files are kept unless --force. Writes desktop/src/assets/shops/<slug>.png and the generated list the
// monogram component reads. Logos are provided by Logo.dev (attribution is in the README and NOTICE.md).
import { mkdir, writeFile, access } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SHOPS } from "./shops.mjs";

const token = process.env.LOGO_DEV_TOKEN;
if (!token || !token.startsWith("pk_")) {
  console.error("Set LOGO_DEV_TOKEN to the publishable key (pk_...).");
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(root, "desktop", "src", "assets", "shops");
const listFile = join(root, "desktop", "src", "shared-ui", "shop-monogram", "shop-logos.generated.ts");
const force = process.argv.includes("--force");

await mkdir(outDir, { recursive: true });

const exists = async (path) => access(path).then(() => true, () => false);
const found = [];
const missing = [];

async function fetchLogo(shop) {
  const file = join(outDir, `${shop.slug}.png`);
  if (!force && (await exists(file))) {
    return true;
  }

  const url = `https://img.logo.dev/${encodeURIComponent(shop.domain)}?token=${token}&size=128&format=png&fallback=404`;
  let response = await fetch(url);
  // The service limits bursts: wait as long as it asks, then try again.
  for (let attempt = 0; response.status === 429 && attempt < 5; attempt++) {
    const wait = Number(response.headers.get("retry-after")) || 60;
    console.log(`rate limited, waiting ${wait}s (${shop.slug})`);
    await new Promise((resolve) => setTimeout(resolve, (wait + 1) * 1000));
    response = await fetch(url);
  }
  if (!response.ok) {
    return false;
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 200) {
    return false;
  }
  await writeFile(file, bytes);
  return true;
}

// One at a time, politely.
const queue = [...SHOPS];
await Promise.all(
  Array.from({ length: 1 }, async () => {
    while (queue.length) {
      const shop = queue.shift();
      try {
        (await fetchLogo(shop)) ? found.push(shop) : missing.push(shop);
      } catch (error) {
        missing.push(shop);
        console.error(`${shop.slug}: ${error.message}`);
      }
    }
  })
);

found.sort((a, b) => SHOPS.indexOf(a) - SHOPS.indexOf(b));

const entries = found
  .map((shop) => `  { slug: ${JSON.stringify(shop.slug)}, name: ${JSON.stringify(shop.name)}, aliases: ${JSON.stringify(shop.aliases)} },`)
  .join("\n");

await writeFile(
  listFile,
  `// Generated by scripts/shop-logos/download-shop-logos.mjs from scripts/shop-logos/shops.mjs. Do not edit.
export interface ShopLogo {
  slug: string;
  name: string;
  aliases: string[];
}

export const SHOP_LOGOS: ShopLogo[] = [
${entries}
];
`
);

console.log(`${found.length} logos in place, ${missing.length} without one.`);
if (missing.length) {
  console.log("No logo for: " + missing.map((shop) => shop.slug).join(", "));
}
